// API base: VITE_API_BASE if set, else the dev-server /api proxy (vite.config.ts).
const BASE = (import.meta.env.VITE_API_BASE as string) || "/api";

/* ------------------------------------------------------------------ auth
 * Staff sign-in token lives in sessionStorage (cleared when the tab closes,
 * never in localStorage). Learners and referrers never need one.
 */
export type StaffRole = "reviewer" | "panel_lead" | "programme_admin" | "auditor" | "school_staff";
export interface StaffUser { id: string; email: string; display_name: string; role: StaffRole; school_id: string | null; }

const TOKEN_KEY = "kuza_staff_token";
const USER_KEY = "kuza_staff_user";

function store(): Storage | null { try { return window.sessionStorage; } catch { return null; } }
export function getToken(): string | null { return store()?.getItem(TOKEN_KEY) ?? null; }
export function getStoredUser(): StaffUser | null {
  try { const u = store()?.getItem(USER_KEY); return u ? JSON.parse(u) : null; } catch { return null; }
}
export function signOut(): void {
  store()?.removeItem(TOKEN_KEY); store()?.removeItem(USER_KEY);
  window.dispatchEvent(new Event("kuza-auth-changed"));
}

async function authed(path: string, init: RequestInit = {}): Promise<Response> {
  const token = getToken();
  const headers = new Headers(init.headers);
  if (token) headers.set("Authorization", `Bearer ${token}`);
  if (init.body) headers.set("Content-Type", "application/json");
  const r = await fetch(`${BASE}${path}`, { ...init, headers });
  if (r.status === 401) signOut(); // expired or deactivated: back to sign-in
  return r;
}

async function detail(r: Response, fallback: string): Promise<string> {
  try { const j = await r.json(); return typeof j.detail === "string" ? j.detail : fallback; } catch { return fallback; }
}

export async function login(email: string, password: string): Promise<StaffUser> {
  const r = await fetch(`${BASE}/auth/login`, {
    method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ email, password }),
  });
  if (!r.ok) throw new Error(await detail(r, `Sign-in failed (${r.status})`));
  const j = await r.json();
  store()?.setItem(TOKEN_KEY, j.token);
  store()?.setItem(USER_KEY, JSON.stringify(j.user));
  window.dispatchEvent(new Event("kuza-auth-changed"));
  return j.user;
}

