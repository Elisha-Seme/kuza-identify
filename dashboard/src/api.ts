export type Bi = { en: string; sw: string };
export interface BankItem {
  id: string; domain: string; difficulty: number; type: string; tier: string;
  prompt: Bi; image?: string; image_after?: string; image_png?: string; show_seconds?: number;
  choices?: Bi[]; text_fallback?: Bi; hints?: Bi[]; response_modes?: string[]; delivery?: string[];
  audio_only?: boolean; replaces?: string; show_script?: Bi; ask_prompt?: Bi;
}
export interface Bank { session_intro: Bi; control_words?: Record<string, Record<string, string[]>>; items: BankItem[]; }

/** Item pictures are served by this dashboard at /items/<path>. */
export const itemAsset = (p: string) => `/items/${p}`;

/** The whole bank from the API; falls back to the copy shipped with the
 * dashboard (same content, generated by tools/item-bank) so Kuza Play still
 * works offline or before the API is redeployed. */
export async function getBank(): Promise<Bank> {
  try {
    const r = await fetch(`${BASE}/screening/items/all`);
    if (r.ok) return await r.json();
  } catch { /* fall through */ }
  const r = await fetch("/items/bank.json");
  if (!r.ok) throw new Error("Could not load the puzzles.");
  return r.json();
}

