/** School staff / admins: start a real screening session for a consented learner. */
export async function startSession(learnerId: string, channel: "web" | "whatsapp" | "sms" | "ussd", language: "en" | "sw"): Promise<{ session_id: string; item_id: string | null }> {
  const r = await authed("/screening/sessions", {
    method: "POST", body: JSON.stringify({ learner_id: learnerId, channel, language }),
  });
  if (!r.ok) throw new Error(await detail(r, `Could not start the session (${r.status})`));
  return r.json();
}

export async function bindPhone(channel: "whatsapp" | "sms" | "ussd", phone: string, sessionId: string): Promise<void> {
  const path = channel === "whatsapp" ? "/screening/webhook/bind" : `/screening/webhook/${channel}/bind`;
  // Phone number in the POST body, never the URL (URLs end up in access logs).
  const r = await authed(path, { method: "POST", body: JSON.stringify({ phone, session_id: sessionId }) });
  if (!r.ok) throw new Error(await detail(r, `Could not link the phone (${r.status})`));
}
